_cached = None


def qicon() -> QIcon:
    """各サイズの QPixmap を束ねた QIcon を返す(作って使い回す)。"""
    global _cached
    if _cached is not None:
        return _cached
    icon = QIcon()
    for size, rows in PIXELS.items():
        data = bytearray()
        for row in rows:
            for ch in row:
                data += bytes(PALETTE[ch])
        img = QImage(bytes(data), size, size, size * 4,
                     QImage.Format_RGBA8888).copy()
        icon.addPixmap(QPixmap.fromImage(img))
    _cached = icon
    return icon

