_cached = {}


def _build(glyph_only: bool) -> QIcon:
    icon = QIcon()
    for size, rows in PIXELS.items():
        data = bytearray()
        for row in rows:
            for ch in row:
                if glyph_only and ch == ".":
                    data += bytes((0, 0, 0, 0))
                else:
                    data += bytes(PALETTE[ch])
        img = QImage(bytes(data), size, size, size * 4,
                     QImage.Format_RGBA8888).copy()
        icon.addPixmap(QPixmap.fromImage(img))
    return icon


def qicon() -> QIcon:
    """白地つきの QIcon(窓・タスクバー用。作って使い回す)。"""
    if "full" not in _cached:
        _cached["full"] = _build(False)
    return _cached["full"]


def qicon_glyph() -> QIcon:
    """字だけ(白地なし)の QIcon。メニューの行用で、地の色に馴染む。"""
    if "glyph" not in _cached:
        _cached["glyph"] = _build(True)
    return _cached["glyph"]
