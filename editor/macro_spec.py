def build_ai_request(prompt=None):
    """AI へ渡す一式(依頼文 + 仕様書全文)を組み立てる。

    prompt が無ければ既定の依頼文を使う。依頼文に
    プレースホルダ行があれば仕様書全文で置き換え、無ければ
    末尾へ仕様書全文を足す。"""
    if prompt is None:
        prompt = PROMPT_TEXT
    if PLACEHOLDER in prompt:
        return prompt.replace(PLACEHOLDER, SPEC_TEXT)
    if not prompt.endswith("\n"):
        prompt += "\n"
    return prompt + SPEC_TEXT
