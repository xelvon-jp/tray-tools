    '- 登録したマクロは設定の中に `{名前: {"commands": [命令の列]}}` または `{名前: {"python": "ソース", "key": "Ctrl+Alt+1"}}` の形で持たれ、マクロ画面のプルダウンから選んで実行したり、キーを割り当てて呼んだりできます。\n'
